const LANG = { cur: (() => { try { return localStorage.getItem("qs_lang") || "ru"; } catch { return "ru"; } })() };
function t(s, v) {
  let r = LANG.cur === "kz" && KZ[s] ? KZ[s] : s;
  if (v) for (const k in v) r = r.split("{" + k + "}").join(v[k]);
  return r;
}
const TR_ORIG = new WeakMap();
function translate(root = document.body) {
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n; (n = w.nextNode());) {
    if (n.parentElement.closest("script,style,.contract,[data-notr]")) continue;
    let o = TR_ORIG.get(n); if (o === undefined) { o = n.nodeValue; TR_ORIG.set(n, o); }
    const k = o.trim(); if (!k) continue;
    const v = LANG.cur === "kz" && KZ[k];
    n.nodeValue = v ? o.replace(k, v) : o;
  }
  root.querySelectorAll("[placeholder]").forEach(e => { if (!e.dataset.ph) e.dataset.ph = e.placeholder; e.placeholder = t(e.dataset.ph); });
  document.documentElement.lang = LANG.cur === "kz" ? "kk" : "ru";
}
